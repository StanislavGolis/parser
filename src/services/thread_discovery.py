# src/services/thread_discovery.py
"""Ключ прогресса сканирования каталога раздела («Загрузить треды» в админке).

Само сканирование живёт в `api/routes/admin.py` (`_run_board_scan`) и работает
через `ScanPlanner` + адаптер источника, поэтому один и тот же код обслуживает
2ch (`catalog.json`) и сайты (страницы категории). Здесь остался только ключ
Redis, по которому админка опрашивает прогресс.
"""


def scan_key(slug: str) -> str:
    """Ключ прогресса сканирования раздела в Redis."""
    return f"scan:board:{slug}"

